#!/usr/bin/env node
/**
 * Prune vendor/dither-ui to the components this app actually uses, and
 * regenerate a slim index.ts barrel. Run after syncing from upstream
 * (called by scripts/update-dither-ui.sh) or standalone:
 *
 *   node scripts/prune-dither-ui.mjs
 */
import { existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve('vendor/dither-ui')

/** Entry modules we use, mapped to the barrel lines they contribute. */
const ENTRIES = [
  // charts
  'area-chart.ts',
  'bar-chart.ts',
  'pie-chart.ts',
  'Area.vue',
  'Bar.vue',
  'Pie.vue',
  'Grid.vue',
  'XAxis.vue',
  'YAxis.vue',
  'Legend.vue',
  'Tooltip.vue',
  // widgets
  'DitherAvatar.vue',
  'DitherButton.vue',
  'DitherGradient.vue',
]

const BARREL = `// Slim barrel — regenerated by scripts/prune-dither-ui.mjs
export { AreaChart, LineChart } from "./area-chart"
export { BarChart } from "./bar-chart"
export { PieChart } from "./pie-chart"
export { default as Area } from "./Area.vue"
export { default as Bar } from "./Bar.vue"
export { default as Pie } from "./Pie.vue"
export { default as Grid } from "./Grid.vue"
export { default as XAxis } from "./XAxis.vue"
export { default as YAxis } from "./YAxis.vue"
export { default as Legend } from "./Legend.vue"
export { default as Tooltip } from "./Tooltip.vue"
export { default as DitherAvatar } from "./DitherAvatar.vue"
export { default as DitherButton } from "./DitherButton.vue"
export { default as DitherGradient } from "./DitherGradient.vue"
export type { ChartConfig } from "./chart-context"
export type { DitherColor } from "./palette"
`

const IMPORT_RE = /(?:from|import)\s*\(?\s*["'](\.[^"']+)["']/g

function resolveImport(fromFile, spec) {
  const base = join(fromFile, '..', spec)
  for (const cand of [base, `${base}.ts`, `${base}.vue`, `${base}.js`, join(base, 'index.ts')])
    if (existsSync(cand) && statSync(cand).isFile()) return cand
  return null
}

const keep = new Set(['package.json', 'README.md', 'AGENTS.md'])
const queue = ENTRIES.map(e => join(root, e))
for (const e of ENTRIES) keep.add(e)
keep.add('chart-context.ts')
keep.add('palette.ts')

while (queue.length) {
  const file = queue.pop()
  const src = readFileSync(file, 'utf8')
  // strip <script> blocks in .vue handled implicitly — imports appear there too
  for (const match of src.matchAll(IMPORT_RE)) {
    const resolved = resolveImport(file, match[1])
    if (!resolved) continue
    const rel = resolved.slice(root.length + 1)
    if (!keep.has(rel)) {
      keep.add(rel)
      queue.push(resolved)
    }
  }
}

const all = readdirSync(root).filter(f => statSync(join(root, f)).isFile())
const removed = all.filter(f => !keep.has(f))
for (const f of removed) rmSync(join(root, f))

// subdirectories: kit is flat, but remove any dir not referenced
for (const f of readdirSync(root))
  if (statSync(join(root, f)).isDirectory()) rmSync(join(root, f), { recursive: true })

writeFileSync(join(root, 'index.ts'), BARREL)
console.log(`pruned ${removed.length} files, kept ${keep.size}`)
